"""Design demo 4: shape design through large rotation.

A pre-curved cantilever strip is loaded by an end moment at M/Mmax = 0.5.
The design variables are four initial centerline heights; the target is the
tip position generated by a known initial curvature.  The state is solved with
the nonlinear production energy; no rotational design variables are used.
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import torch

from checkerboard_shell.mechanics.energy import make_targets
from experiments.cmame_round4.cantilever import (
    CantileverProblem, MAXIMUM_MOMENT,
)
from experiments.cmame_round4.nonlinear_solver import (
    SolverSettings, solve_load_level,
)
from experiments.cmame_round5.common import (
    DATA, FIGURES, LOGS, lbfgs, write_csv, write_json,
)


NX, NY = 24, 4
LENGTH = 12.0
LOAD = 0.25
X_CONTROL = np.linspace(0.0, LENGTH, 3)
AMPLITUDE = 1.5
ALPHA = 1.0e-6


class CurvedCantileverProblem(CantileverProblem):
    def __init__(self, nx, ny, controls):
        super().__init__(nx, ny)
        x_line = self.reference[0, :, 0].detach().cpu().numpy()
        z_line = np.interp(x_line, X_CONTROL, controls)
        self.reference = self.reference.clone()
        self.reference[..., 2] = torch.as_tensor(
            np.tile(z_line, (ny + 1, 1)), dtype=self.reference.dtype)
        self.targets = make_targets(self.reference, self.hx, self.hy)
        self.initial = torch.zeros((nx - 1) * 2,
                                   dtype=self.reference.dtype)


def _settings(single=True):
    return SolverSettings(
        initial_step=0.05, maximum_step=0.1, minimum_step=0.002,
        residual_tolerance=(1.0e-5 if single else 1.0e-7),
        maximum_newton_iterations=(60 if single else 30),
        eigenvalue_relative_floor=1.0e-10)


def _single_step(problem, initial):
    anchor = problem.end_tangent(problem.current(initial)).detach()
    previous_angle = problem.turning_angle(problem.current(initial)).detach()
    work_offset = float(LOAD) * MAXIMUM_MOMENT * previous_angle
    potential = lambda x: problem.potential(
        x, LOAD, anchor, work_offset)
    return solve_load_level(potential, initial, _settings(single=True))


def _continuation(problem, initial):
    values = initial.clone()
    last = None
    for load in np.linspace(0.05, LOAD, 10):
        anchor = problem.end_tangent(problem.current(values)).detach()
        previous_angle = problem.turning_angle(
            problem.current(values)).detach()
        work_offset = float(load) * MAXIMUM_MOMENT * previous_angle
        potential = lambda x, load=load, anchor=anchor, work_offset=work_offset: (
            problem.potential(x, load, anchor, work_offset))
        last = solve_load_level(potential, values, _settings(single=False))
        values = last["coordinates"].detach()
        if last["status"] != "CONVERGED":
            break
    return last


def _solve(controls, initial=None):
    problem = CurvedCantileverProblem(NX, NY, controls)
    if initial is None:
        result = _continuation(problem, problem.initial)
    else:
        result = _single_step(problem, initial)
        if result["status"] != "CONVERGED":
            result = _continuation(problem, problem.initial)
    return problem, result


def _tip(result, problem):
    return problem.tip(result["coordinates"])


def _full(values):
    return np.array([0.0, float(values[0]), float(values[1])])


def run() -> dict:
    h_true = AMPLITUDE * (X_CONTROL / LENGTH) ** 2
    p0 = np.zeros(2)
    problem_base, result_base = _solve(_full(p0))
    base_initial = result_base["coordinates"]
    problem_true, result_true = _solve(h_true, initial=base_initial)
    target = _tip(result_true, problem_true)

    history: list[dict] = []

    def objective(values, initial=base_initial):
        problem, result = _solve(_full(values), initial=initial)
        tip = _tip(result, problem)
        value = ((tip[0] - target[0]) ** 2 + (tip[1] - target[1]) ** 2
                 + ALPHA * float(values @ values))
        return value, tip, result["status"]

    def function(values):
        value, _, _ = objective(values, initial=base_initial)
        gradient = np.zeros_like(values)
        epsilon = 1.0e-4
        for index in range(values.size):
            direction = np.zeros_like(values)
            direction[index] = epsilon
            plus, _, _ = objective(values + direction,
                                   initial=base_initial)
            minus, _, _ = objective(values - direction,
                                    initial=base_initial)
            gradient[index] = (plus - minus) / (2.0 * epsilon)
        return value, gradient

    def callback(values, value, gradient):
        _, tip, status = objective(values, initial=base_initial)
        return {
            "tip_x": float(tip[0]),
            "tip_z": float(tip[1]),
            "tip_error": float(np.hypot(tip[0] - target[0],
                                        tip[1] - target[1])),
            "solver_status": status,
        }

    result, history = lbfgs(function, p0, max_iterations=8,
                            callback=callback)
    h_opt = _full(result.x)
    problem_opt, result_opt = _solve(h_opt, initial=base_initial)
    tip_opt = _tip(result_opt, problem_opt)
    tip_error = float(np.hypot(tip_opt[0] - target[0],
                               tip_opt[1] - target[1]))
    payload = {
        "case": "large_rotation_shape_design",
        "mesh": "cantilever_strip_24x4",
        "load": "end moment at M/Mmax=0.25",
        "design_variables": 2,
        "free_dofs": 2 * (NX - 1),
        "target_tip": [float(target[0]), float(target[1])],
        "optimal_tip": [float(tip_opt[0]), float(tip_opt[1])],
        "tip_error": tip_error,
        "objective_initial": float(history[0]["objective"]),
        "objective_optimal": float(result.fun),
        "iterations": int(result.nit),
        "success": bool(result.success),
        "message": str(result.message),
        "h_true": h_true.tolist(),
        "h_opt": h_opt.tolist(),
        "history": history,
        "note": (
            "Nonlinear equilibrium at fixed end moment; finite-difference "
            "design gradient; no rotational design variables."),
    }
    write_json(DATA/"large_rotation_design.json", payload)
    write_csv(DATA/"large_rotation_design_history.csv", history)

    figure, axes = plt.subplots(1, 2, figsize=(10.5, 3.8))
    x_line = np.linspace(0.0, LENGTH, 200)
    for label, controls, colour in (
        ("target initial shape", h_true, "0.55"),
        ("optimized initial shape", h_opt, "0.1"),
    ):
        z_line = np.interp(x_line, X_CONTROL, controls)
        axes[0].plot(x_line, z_line, color=colour, label=label)
    axes[0].set_xlabel("$x$"); axes[0].set_ylabel("$z_0$")
    axes[0].set_title("initial centerline")
    axes[0].legend(fontsize=8)
    axes[1].semilogy([row["iteration"] for row in history],
                     [row["tip_error"] for row in history],
                     marker="o", color="0.1")
    axes[1].set_xlabel("iteration"); axes[1].set_ylabel("tip error")
    axes[1].set_title("tip-position convergence")
    axes[1].grid(True, alpha=0.25)
    figure.tight_layout()
    FIGURES.mkdir(parents=True, exist_ok=True)
    figure.savefig(FIGURES/"Figure_R5_large_rotation_design.png", dpi=220)
    figure.savefig(FIGURES/"Figure_R5_large_rotation_design.pdf")
    plt.close(figure)

    write_json(LOGS/"large_rotation_design_summary.json", {
        "tip_error": tip_error,
        "iterations": payload["iterations"],
        "design_variables": payload["design_variables"],
    })
    return payload


if __name__ == "__main__":
    print(json.dumps(run(), indent=2)[:4000])
