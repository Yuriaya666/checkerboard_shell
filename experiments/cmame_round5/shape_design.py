"""Design demo 3: reference-shape optimization.

A clamped cantilever plate is loaded at its free end.  The reference height
field is parameterised by a 4x4 control lattice (the clamped x=0 column is
fixed), and the target displacement field is generated by a known smooth
reference shape.  The design gradient is computed by central differences of
the linear state solves; the state tangent is the production sparse rank-one
tangent.
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import torch

from checkerboard_shell import IsotropicMaterial, NodalLoad
from experiments.cmame_round5.common import (
    DATA, FIGURES, HERE, LOGS, bilinear_controls, cantilever_mesh,
    clamped_model, control_grid, design_indices, force_matrix, linear_solve, node_id,
    selection_matrix, tangent_at_reference, write_csv, write_json, lbfgs,
)


NX, NY = 12, 8
WIDTH, HEIGHT = 1.0, 0.6
NX_CONTROL, NY_CONTROL = 4, 4
AMPLITUDE = 0.01
BASE_AMPLITUDE = 0.05
ALPHA = 1.0e-8
BETA = 1.0e-5


def _full_controls(values):
    x_control, y_control = control_grid(
        None, NX_CONTROL, NY_CONTROL, WIDTH, HEIGHT)
    full = np.zeros((NY_CONTROL, NX_CONTROL))
    for value, (j, i) in zip(values, design_indices(NX_CONTROL, NY_CONTROL)):
        full[j, i] = value
    return full


def _true_controls():
    x_control, y_control = control_grid(
        None, NX_CONTROL, NY_CONTROL, WIDTH, HEIGHT)
    xx, yy = np.meshgrid(x_control, y_control)
    full = AMPLITUDE * np.sin(0.5 * np.pi * xx / WIDTH) * (
        0.5 + 0.5 * np.cos(np.pi * (yy - 0.5 * HEIGHT) / HEIGHT))
    full[:, 0] = 0.0
    return full


def _design_vector(full):
    return np.array([full[j, i]
                     for (j, i) in design_indices(NX_CONTROL, NY_CONTROL)])


def _reference_mesh(values):
    base = cantilever_mesh(NX, NY, WIDTH, HEIGHT)
    x_control, y_control = control_grid(
        base, NX_CONTROL, NY_CONTROL, WIDTH, HEIGHT)
    perturbation = bilinear_controls(base, _full_controls(values),
                                     x_control, y_control)
    x = base.reference_vertices[..., 0].detach().cpu().numpy()
    y = base.reference_vertices[..., 1].detach().cpu().numpy()
    # A pre-curved base breaks the up-down symmetry of a flat plate; without
    # it the transverse response is even in the reference height and the sign
    # of the design is not identifiable.
    z_base = BASE_AMPLITUDE * np.sin(0.5 * np.pi * x / WIDTH) * (
        0.5 + 0.5 * np.cos(np.pi * (y - 0.5 * HEIGHT) / HEIGHT))
    return cantilever_mesh(NX, NY, WIDTH, HEIGHT,
                           heights=z_base + perturbation)


def _load(mesh):
    tip = [node_id(mesh, NX, j) for j in range(NY + 1)]
    return NodalLoad.total_force(mesh, (0.0, 0.0, -0.02), node_ids=tip)


def _state(values):
    mesh = _reference_mesh(values)
    material = IsotropicMaterial(2.0e5, 0.3, 0.04)
    model = clamped_model(mesh, material, _load(mesh))
    tangent, residual, audit = tangent_at_reference(model)
    q, _ = linear_solve(tangent, -residual)
    nodes = [node_id(mesh, i, j) for j in range(NY + 1)
             for i in range(2, NX + 1)]
    S = selection_matrix(model, nodes)
    return mesh, model, q, S


def _objective(values, S, target):
    _, _, q, _ = _state(values)
    r = S @ q - target
    return float(r @ r + ALPHA * values @ values + BETA * _roughness(values))


def _roughness(values):
    full = _full_controls(values)
    dx = np.diff(full, axis=1)
    dy = np.diff(full, axis=0)
    return float(np.sum(dx * dx) + np.sum(dy * dy))


def _finite_difference_gradient(values, S, target, epsilon=1.0e-6):
    gradient = np.zeros_like(values)
    for index in range(values.size):
        direction = np.zeros_like(values)
        direction[index] = epsilon
        plus = _objective(values + direction, S, target)
        minus = _objective(values - direction, S, target)
        gradient[index] = (plus - minus) / (2.0 * epsilon)
    return gradient


def run() -> dict:
    p_true = _design_vector(_true_controls())
    _, _, q_true, S = _state(p_true)
    target = S @ q_true
    p0 = np.zeros_like(p_true)

    history: list[dict] = []

    def function(values):
        value = _objective(values, S, target)
        gradient = _finite_difference_gradient(values, S, target)
        return value, gradient

    def callback(values, value, gradient):
        _, _, q, _ = _state(values)
        error = float(np.linalg.norm(S @ q - target)
                      / max(np.linalg.norm(target), 1e-30))
        height_error = float(np.linalg.norm(values - p_true)
                             / max(np.linalg.norm(p_true), 1e-30))
        return {
            "displacement_error": error,
            "height_error": height_error,
        }

    result, history = lbfgs(function, p0, max_iterations=20,
                            callback=callback)
    p_opt = result.x
    _, _, q_opt, _ = _state(p_opt)
    displacement_error = float(np.linalg.norm(S @ q_opt - target)
                               / max(np.linalg.norm(target), 1e-30))
    height_error = float(np.linalg.norm(p_opt - p_true)
                         / max(np.linalg.norm(p_true), 1e-30))
    payload = {
        "case": "reference_shape_optimization",
        "mesh": "cantilever_plate_12x8",
        "material": {"E": 2.0e5, "nu": 0.3, "t": 0.04},
        "design_variables": int(p0.size),
        "free_dofs": int(S.shape[1]),
        "observations": int(S.shape[0]),
        "objective_initial": float(history[0]["objective"]),
        "objective_optimal": float(result.fun),
        "displacement_relative_error": displacement_error,
        "height_relative_error": height_error,
        "iterations": int(result.nit),
        "success": bool(result.success),
        "message": str(result.message),
        "p_true": p_true.tolist(),
        "p_opt": p_opt.tolist(),
        "history": history,
        "note": (
            "State tangent is the production sparse rank-one tangent; the "
            "design derivative is central finite difference of linear state "
            "solves."),
    }
    write_json(DATA/"shape_design.json", payload)
    write_csv(DATA/"shape_design_history.csv", history)

    # Figure: true / initial / optimized height fields and convergence.
    x_control, y_control = control_grid(
        None, NX_CONTROL, NY_CONTROL, WIDTH, HEIGHT)
    fields = [
        ("target reference", _true_controls()),
        ("initial reference", _full_controls(p0)),
        ("optimized reference", _full_controls(p_opt)),
    ]
    figure, axes = plt.subplots(1, 4, figsize=(16.0, 3.6))
    for axis, (title, field) in zip(axes[:3], fields):
        image = axis.imshow(field, origin="lower", cmap="coolwarm",
                            extent=(0, WIDTH, 0, HEIGHT), aspect="auto")
        figure.colorbar(image, ax=axis, fraction=0.046, pad=0.04)
        axis.set_title(title)
        axis.set_xlabel("$x$"); axis.set_ylabel("$y$")
    axes[3].semilogy([row["iteration"] for row in history],
                     [row["displacement_error"] for row in history],
                     marker="o", color="0.1")
    axes[3].set_title("target-shape error")
    axes[3].set_xlabel("iteration")
    axes[3].set_ylabel("relative displacement error")
    axes[3].grid(True, alpha=0.25)
    figure.tight_layout()
    FIGURES.mkdir(parents=True, exist_ok=True)
    figure.savefig(FIGURES/"Figure_R5_shape_design.png", dpi=220)
    figure.savefig(FIGURES/"Figure_R5_shape_design.pdf")
    plt.close(figure)

    write_json(LOGS/"shape_design_summary.json", {
        "displacement_relative_error": displacement_error,
        "height_relative_error": height_error,
        "iterations": payload["iterations"],
        "design_variables": payload["design_variables"],
    })
    return payload


if __name__ == "__main__":
    print(json.dumps(run(), indent=2)[:4000])
