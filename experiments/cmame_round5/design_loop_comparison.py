"""Compare the position-only adjoint design loop with a black-box MITC4 FD loop.

Both solve the same 9-actuator target-shape problem.  The comparison is
implementation-level: the standard-shell loop uses finite differences because
OpenSees does not expose an adjoint; the position-only loop uses the exact
production tangent.
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from experiments.cmame_round5.common import DATA, FIGURES, OUT, write_json


def run() -> dict:
    fair = json.loads((DATA/"fair_fd_adjoint.json").read_text())
    fd = json.loads((DATA/"fd_vs_fd.json").read_text())
    mt = json.loads((DATA/"fd_vs_fd_mitc4_own.json").read_text())
    cb_adj = fair["rows"][0]
    cb_fd = fd["checkerboard"]
    rows = [
        {
            "method": "Checkerboard + adjoint",
            "design_variables": fair["design_variables"],
            "free_dofs": fair["free_dofs"],
            "iterations": cb_adj["iterations"],
            "work_units": cb_adj["solves"],
            "work_label": "linear solves",
            "runtime_seconds": cb_adj["total_seconds"],
            "target_error": cb_adj["target_error"],
        },
        {
            "method": "Checkerboard + finite difference",
            "design_variables": fd["design_variables"],
            "free_dofs": cb_fd["free_dofs"],
            "iterations": cb_fd["iterations"],
            "work_units": cb_fd["solves"],
            "work_label": "linear solves",
            "runtime_seconds": cb_fd["total_seconds"],
            "target_error": cb_fd["target_error"],
        },
        {
            "method": "MITC4 + finite difference",
            "design_variables": fd["design_variables"],
            "free_dofs": mt["free_dofs"],
            "iterations": mt["iterations"],
            "work_units": mt["analyses"],
            "work_label": "forward analyses",
            "runtime_seconds": mt["optimization_seconds"],
            "target_error": mt["target_error"],
        },
    ]
    write_json(DATA/"design_loop_comparison.json", rows)

    lines = [
        "# Design-loop comparison: three layers",
        "",
        "Same 9-actuator target-shape problem, same `12x8` mesh/BC/observations.",
        "Each model uses its own target generated by the same `f_true`; target",
        "errors are not an accuracy comparison.  Layer 1 (adjoint vs FD) uses",
        "the same Checkerboard model, linear solver and L-BFGS settings;",
        "model/tangent assembly is included in both totals.  Layer 3 uses a",
        "black-box OpenSees ShellMITC4 model with finite differences.",
        "",
        "| method | design vars | free DOF | iterations | work | total time (s) | target error |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for row in rows:
        lines.append(
            f"| {row['method']} | {row['design_variables']} | {row['free_dofs']} | "
            f"{row['iterations']} | {row['work_units']} {row['work_label']} | "
            f"{row['runtime_seconds']:.2f} | {100.0*row['target_error']:.4f}% |")
    lines.extend([
        "",
        f"Layer 1: adjoint `{rows[0]['work_units']}` solves vs FD "
        f"`{rows[1]['work_units']}` solves, a "
        f"`{rows[1]['work_units']/rows[0]['work_units']:.1f}x` reduction; "
        f"optimization time `{cb_adj['optimization_seconds']:.2f}` vs "
        f"`{cb_fd['optimization_seconds']:.2f}` s; total time is dominated by "
        f"the common `{cb_fd['build_seconds']:.2f}` s assembly.",
        "",
        f"Layer 2: `{rows[0]['free_dofs']}` vs `{rows[2]['free_dofs']}` free DOF, "
        f"about `{rows[0]['free_dofs']/rows[2]['free_dofs']:.2f}` state.",
        "",
        f"Layer 3: black-box MITC4 FD takes `{rows[2]['runtime_seconds']:.2f}` s "
        f"vs `{rows[0]['runtime_seconds']:.2f}` s for the position-only adjoint "
        f"loop, about `{rows[2]['runtime_seconds']/rows[0]['runtime_seconds']:.1f}x`.",
        "This is implementation-level: the MITC4 loop rebuilds the model per",
        "analysis and uses FD; a MITC4 adjoint would reduce its work units.",
        "",
        f"The missing same-gradient-method comparison, Checkerboard FD vs MITC4 FD, "
        f"is `{rows[1]['runtime_seconds']:.2f}` vs "
        f"`{rows[2]['runtime_seconds']:.2f}` s (about "
        f"`{rows[2]['runtime_seconds']/rows[1]['runtime_seconds']:.1f}x`) in `FD_VS_FD.md`.",
    ])
    (OUT/"DESIGN_LOOP_COMPARISON.md").write_text("\n".join(lines) + "\n",
                                                encoding="utf-8")
    figure, axes = plt.subplots(1, 3, figsize=(13.2, 3.8))
    labels = [row["method"].replace(" + ", "\n+ ") for row in rows]
    colours = ["0.15", "0.4", "0.65"]
    for axis, key, title, scale in (
        (axes[0], "runtime_seconds", "total time [s]", "log"),
        (axes[1], "work_units", "work units", "log"),
        (axes[2], "free_dofs", "free DOF", "linear"),
    ):
        values = [row[key] for row in rows]
        axis.bar(labels, values, color=colours)
        axis.set_title(title)
        axis.tick_params(axis="x", labelsize=7)
        if scale == "log":
            axis.set_yscale("log")
        for index, value in enumerate(values):
            axis.text(index, value, f"{value:.3g}", ha="center",
                      va="bottom", fontsize=7)
    figure.tight_layout()
    FIGURES.mkdir(parents=True, exist_ok=True)
    figure.savefig(FIGURES/"Figure_R5_design_loop_comparison.png", dpi=220)
    figure.savefig(FIGURES/"Figure_R5_design_loop_comparison.pdf")
    plt.close(figure)
    return {"rows": rows}


if __name__ == "__main__":
    print(json.dumps(run(), indent=2))
