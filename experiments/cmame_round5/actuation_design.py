"""Design demo 2: actuation shape control with adjoint gradients.

A clamped cantilever plate is actuated by nine nodal forces on a patch near the
free end.  The target displacement field is generated by a known smooth force
distribution.  The inverse problem is solved with L-BFGS using the exact
adjoint gradient of the production tangent.
"""

from __future__ import annotations

import json
import time
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from experiments.cmame_round5.common import (
    DATA, FIGURES, LOGS, cantilever_mesh, clamped_model, force_matrix,
    gaussian_patch, linear_solve, node_id, selection_matrix,
    tangent_at_reference, write_csv, write_json, lbfgs,
)
from checkerboard_shell import IsotropicMaterial, NodalLoad


FORCE_NODES = [(i, j) for j in (2, 4, 6) for i in (9, 10, 11)]
OBS_NODES = [(i, j) for j in range(9) for i in range(2, 13)]
ALPHA = 1.0e-10
_COUNTER = {"linear_solves": 0}


def build_problem():
    mesh = cantilever_mesh(12, 8)
    material = IsotropicMaterial(2.0e5, 0.3, 0.04)
    model = clamped_model(mesh, material, NodalLoad.zero(mesh))
    tangent, residual, audit = tangent_at_reference(model)
    force_nodes = [node_id(mesh, i, j) for i, j in FORCE_NODES]
    observation_nodes = [node_id(mesh, i, j) for i, j in OBS_NODES]
    P = force_matrix(model, force_nodes)
    S = selection_matrix(model, observation_nodes)

    weights = gaussian_patch(
        mesh, x0=0.82, y0=0.30, sigma_x=0.12, sigma_y=0.12,
        total=0.02, x_range=(0.70, 1.0))
    f_true = np.array([weights[j, i] for i, j in FORCE_NODES])
    q_true, _ = linear_solve(tangent, P @ f_true)
    u_target = S @ q_true
    return {
        "mesh": mesh, "material": material, "model": model,
        "tangent": tangent, "P": P, "S": S, "f_true": f_true,
        "u_target": u_target, "force_nodes": force_nodes,
        "observation_nodes": observation_nodes,
    }


def _solve(tangent, rhs):
    _COUNTER["linear_solves"] += 1
    return linear_solve(tangent, rhs)


def objective(problem, forces):
    q, _ = _solve(problem["tangent"], problem["P"] @ forces)
    r = problem["S"] @ q - problem["u_target"]
    return float(r @ r + ALPHA * forces @ forces), q, r


def gradient(problem, forces):
    q, _ = _solve(problem["tangent"], problem["P"] @ forces)
    r = problem["S"] @ q - problem["u_target"]
    lambda_, _ = _solve(problem["tangent"], 2.0 * problem["S"].T @ r)
    return problem["P"].T @ lambda_ + 2.0 * ALPHA * forces


def run() -> dict:
    started = time.perf_counter()
    problem = build_problem()
    f0 = np.zeros_like(problem["f_true"])

    # Adjoint check against central differences.
    check_indices = (0, 4, 8)
    epsilon = 1.0e-7
    checks = []
    for index in check_indices:
        direction = np.zeros_like(f0)
        direction[index] = epsilon
        plus, _, _ = objective(problem, f0 + direction)
        minus, _, _ = objective(problem, f0 - direction)
        finite = (plus - minus) / (2.0 * epsilon)
        exact = gradient(problem, f0)[index]
        checks.append({
            "index": int(index),
            "adjoint": float(exact),
            "finite_difference": float(finite),
            "relative_error": float(abs(exact - finite)
                                    / max(abs(finite), 1e-30)),
        })

    _COUNTER["linear_solves"] = 0

    def function(values):
        value, _, _ = objective(problem, values)
        return value, gradient(problem, values)

    history: list[dict] = []

    def callback(values, value, grad):
        history.append({
            "iteration": len(history),
            "objective": float(value),
            "gradient_norm": float(np.linalg.norm(grad)),
            "force_error": float(np.linalg.norm(values - problem["f_true"])
                                 / np.linalg.norm(problem["f_true"])),
        })

    result, history = lbfgs(function, f0, max_iterations=30,
                            callback=callback)
    runtime = time.perf_counter() - started
    f_opt = result.x
    value_opt, q_opt, residual_opt = objective(problem, f_opt)
    value_true, q_true, _ = objective(problem, problem["f_true"])
    displacement_error = float(np.linalg.norm(residual_opt)
                               / max(np.linalg.norm(problem["u_target"]), 1e-30))
    force_error = float(np.linalg.norm(f_opt - problem["f_true"])
                        / np.linalg.norm(problem["f_true"]))

    payload = {
        "case": "actuation_shape_control",
        "mesh": "cantilever_plate_12x8",
        "material": {"E": 2.0e5, "nu": 0.3, "t": 0.04},
        "force_nodes": problem["force_nodes"],
        "observation_nodes": problem["observation_nodes"],
        "design_variables": int(f0.size),
        "free_dofs": int(problem["model"].boundary_conditions.free_mask.sum()),
        "objective_initial": float(history[0]["objective"]),
        "objective_optimal": float(value_opt),
        "target_objective": float(value_true),
        "displacement_relative_error": displacement_error,
        "force_relative_error": force_error,
        "iterations": int(result.nit),
        "runtime_seconds": float(runtime),
        "linear_solves": int(_COUNTER["linear_solves"]),
        "success": bool(result.success),
        "message": str(result.message),
        "adjoint_checks": checks,
        "max_adjoint_check_relative_error": max(
            check["relative_error"] for check in checks),
        "history": history,
    }
    write_json(DATA/"actuation_design.json", payload)
    write_csv(DATA/"actuation_design_history.csv", history)

    # Figure: target vs optimized displacement, force recovery, convergence.
    mesh = problem["mesh"]
    observation_xy = np.array([
        [mesh.reference_vertices[j, i, 0].item(),
         mesh.reference_vertices[j, i, 1].item()]
        for i, j in OBS_NODES])
    target = problem["u_target"]
    optimized = problem["S"] @ q_opt
    figure, axes = plt.subplots(1, 3, figsize=(13.2, 3.9))
    scatter = axes[0].scatter(observation_xy[:, 0], observation_xy[:, 1],
                              c=target, cmap="viridis", s=80)
    figure.colorbar(scatter, ax=axes[0], label="target $u_z$")
    axes[0].set_title("target displacement")
    axes[0].set_xlabel("$x$"); axes[0].set_ylabel("$y$")
    scatter = axes[1].scatter(observation_xy[:, 0], observation_xy[:, 1],
                              c=optimized, cmap="viridis", s=80)
    figure.colorbar(scatter, ax=axes[1], label="optimized $u_z$")
    axes[1].set_title("optimized displacement")
    axes[1].set_xlabel("$x$"); axes[1].set_ylabel("$y$")
    axes[2].semilogy([row["iteration"] for row in history],
                     [row["objective"] for row in history],
                     marker="o", color="0.1")
    axes[2].set_title("L-BFGS convergence")
    axes[2].set_xlabel("iteration"); axes[2].set_ylabel("objective")
    axes[2].grid(True, alpha=0.25)
    figure.tight_layout()
    FIGURES.mkdir(parents=True, exist_ok=True)
    figure.savefig(FIGURES/"Figure_R5_actuation_design.png", dpi=220)
    figure.savefig(FIGURES/"Figure_R5_actuation_design.pdf")
    plt.close(figure)

    write_json(LOGS/"actuation_design_summary.json", {
        "objective_initial": payload["objective_initial"],
        "objective_optimal": payload["objective_optimal"],
        "displacement_relative_error": payload["displacement_relative_error"],
        "force_relative_error": payload["force_relative_error"],
        "iterations": payload["iterations"],
        "adjoint_check_relative_error": payload["max_adjoint_check_relative_error"],
    })
    return payload


if __name__ == "__main__":
    print(json.dumps(run(), indent=2)[:4000])
